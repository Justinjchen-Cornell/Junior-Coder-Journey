# 参考实现（书中示例：水果分类 —— 按"重量×颜色"判断是橙子还是柚子）

# 已知水果库：每个水果两个特征 [重量(克), 颜色深浅(0-1)]
fruits = [
    # 橙子: 轻 + 浅色
    ([140, 0.3], "橙子"), ([150, 0.4], "橙子"), ([130, 0.2], "橙子"),
    # 柚子: 重 + 深色
    ([300, 0.8], "柚子"), ([280, 0.9], "柚子"), ([320, 0.7], "柚子"),
]

# 新来的水果：245 克，颜色 0.5 —— 它是谁？
new_fruit = [245, 0.5]

# 分类方法：找最近的 3 个邻居，投票决定
def euclidean(a, b):
    """欧几里得距离：两点间直线距离 = sqrt(Σ(差值²))"""
    return sum((x - y) ** 2 for x, y in zip(a, b)) ** 0.5

distances = sorted((euclidean(new_fruit, f[0]), f[1]) for f in fruits)
nearest = distances[:3]
print(f"最近 3 个邻居: {nearest}")
